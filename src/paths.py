"""Central path registry for the VHH-SH2 project.

All code must import paths from here. Never hard-code /content/drive or any
local path in another module.

Resolution order
----------------
SHARED:
  1. env var VHH_SHARED          (set by Colab cell or local override)
  2. /content/drive/MyDrive/vhh-sh2   (auto-detected when running on Colab)
  3. None                         (laptop without Drive: toy data only)

DATA:
  1. env var VHH_DATA
  2. SHARED / "data"             (if SHARED is set)
  3. ROOT / "data"               (fallback)

CKPT, MLRUNS: under SHARED when available, else under ROOT.

Usage
-----
    from src.paths import DATA, CKPT, data_dir
    sequences = data_dir("toy") / "vhh_unique.txt"
"""

# TODO(owner: B)

import os
from pathlib import Path

# ── Repo root ─────────────────────────────────────────────────────────────────
ROOT: Path = Path(__file__).parent.parent.resolve()


# ── Detect Google Colab ───────────────────────────────────────────────────────
def _is_colab() -> bool:
    try:
        import google.colab  # noqa: F401

        return True
    except ImportError:
        return False


# ── SHARED (Drive mount point) ────────────────────────────────────────────────
_shared_env = os.environ.get("VHH_SHARED")
if _shared_env:
    SHARED: Path | None = Path(_shared_env)
elif _is_colab():
    SHARED = Path("/content/drive/MyDrive/vhh-sh2")
else:
    SHARED = None

# ── DATA ──────────────────────────────────────────────────────────────────────
_data_env = os.environ.get("VHH_DATA")
if _data_env:
    DATA: Path = Path(_data_env)
elif SHARED is not None:
    DATA = SHARED / "data"
else:
    DATA = ROOT / "data"

# ── Checkpoints & MLflow runs ─────────────────────────────────────────────────
CKPT: Path = (SHARED / "checkpoints") if SHARED else (ROOT / "checkpoints")
MLRUNS: Path = (SHARED / "mlruns") if SHARED else (ROOT / "mlruns")


def data_dir(name: str) -> Path:
    """Return the path for a named data split.

    Parameters
    ----------
    name:
        "toy"  → ROOT/data/toy  (regenerated by ``make toy``; never committed)
        other  → DATA           (real data on Drive or VHH_DATA)
    """
    if name == "toy":
        return ROOT / "data" / "toy"
    return DATA
